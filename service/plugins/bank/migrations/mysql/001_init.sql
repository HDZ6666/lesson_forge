-- 题库插件第一版 MySQL schema。
-- 业务表只保存当前状态；发布批次只保存构建物与发布元数据。

CREATE TABLE IF NOT EXISTS qb_textbook_version (
    version_id           BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    source_provider      VARCHAR(64) NOT NULL COMMENT '来源提供方，由同步/发布器显式提供',
    external_version_id  VARCHAR(64) DEFAULT NULL COMMENT '来源版本 ID',
    version_name         VARCHAR(100) NOT NULL COMMENT '版本名称',
    source_url            VARCHAR(500) DEFAULT NULL COMMENT '来源页面地址',
    is_new                CHAR(1) DEFAULT NULL COMMENT 'sys_yes_no：Y 是，N 否，NULL 未抓取',
    sort_order            INT NOT NULL DEFAULT 0 COMMENT '显示顺序',
    status                CHAR(1) NOT NULL DEFAULT '0' COMMENT 'sys_normal_disable：0 正常，1 停用',
    last_sync_batch_id    BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at          DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    create_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (version_id),
    UNIQUE KEY uk_qb_version_provider_external (source_provider, external_version_id),
    KEY idx_qb_version_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库版本当前数据';

CREATE TABLE IF NOT EXISTS qb_textbook (
    textbook_id           BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    version_id            BIGINT NOT NULL COMMENT '所属版本本地 ID',
    source_provider       VARCHAR(64) NOT NULL COMMENT '来源提供方，由同步/发布器显式提供',
    external_textbook_id  VARCHAR(64) DEFAULT NULL COMMENT '来源教材 ID',
    textbook_name         VARCHAR(100) NOT NULL COMMENT '教材名称',
    grade                 VARCHAR(20) DEFAULT NULL COMMENT 'qb_grade：保留网站中文原值',
    volume                VARCHAR(20) DEFAULT NULL COMMENT 'qb_volume：保留网站中文原值',
    source_url            VARCHAR(500) DEFAULT NULL COMMENT '来源页面地址',
    sort_order            INT NOT NULL DEFAULT 0 COMMENT '显示顺序',
    status                CHAR(1) NOT NULL DEFAULT '0' COMMENT 'sys_normal_disable：0 正常，1 停用',
    last_sync_batch_id    BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at          DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    create_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (textbook_id),
    UNIQUE KEY uk_qb_textbook_provider_external (source_provider, external_textbook_id),
    KEY idx_qb_textbook_version (version_id),
    KEY idx_qb_textbook_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库教材当前数据';

CREATE TABLE IF NOT EXISTS qb_catalog_node (
    catalog_id            BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    textbook_id           BIGINT NOT NULL COMMENT '所属教材本地 ID',
    parent_id             BIGINT DEFAULT NULL COMMENT '父节点本地 ID，顶级节点为空',
    source_provider       VARCHAR(64) NOT NULL COMMENT '来源提供方，由同步/发布器显式提供',
    external_node_id      VARCHAR(64) DEFAULT NULL COMMENT '来源目录节点 ID',
    node_name             VARCHAR(300) NOT NULL COMMENT '目录节点名称',
    node_type             VARCHAR(20) NOT NULL COMMENT 'qb_catalog_node_type：chapter/section/point/other',
    source_url            VARCHAR(500) DEFAULT NULL COMMENT '来源页面地址',
    sort_order            INT NOT NULL DEFAULT 0 COMMENT '显示顺序',
    status                CHAR(1) NOT NULL DEFAULT '0' COMMENT 'sys_normal_disable：0 正常，1 停用',
    last_sync_batch_id    BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at          DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    create_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (catalog_id),
    UNIQUE KEY uk_qb_catalog_provider_external (source_provider, external_node_id),
    KEY idx_qb_catalog_parent (textbook_id, parent_id),
    KEY idx_qb_catalog_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库目录节点当前数据';

CREATE TABLE IF NOT EXISTS qb_question (
    question_id             BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    source_provider         VARCHAR(64) NOT NULL COMMENT '来源提供方，由同步/发布器显式提供',
    external_question_id    VARCHAR(64) DEFAULT NULL COMMENT '来源题目 ID',
    source_url              VARCHAR(500) DEFAULT NULL COMMENT '题目来源地址',
    source_question_no      VARCHAR(64) DEFAULT NULL COMMENT '来源题号',
    source_text             VARCHAR(500) DEFAULT NULL COMMENT '来源完整原文摘要',
    paper_name              VARCHAR(500) DEFAULT NULL COMMENT '来源试卷名称',
    academic_year           VARCHAR(20) DEFAULT NULL COMMENT '学年，例如 25-26',
    year                    SMALLINT DEFAULT NULL COMMENT '年份筛选值',
    grade                   VARCHAR(20) DEFAULT NULL COMMENT 'qb_grade：保留网站中文原值',
    term                    VARCHAR(20) DEFAULT NULL COMMENT 'qb_term：保留网站中文原值',
    province                VARCHAR(50) DEFAULT NULL COMMENT '省份',
    city                    VARCHAR(100) DEFAULT NULL COMMENT '城市',
    district                VARCHAR(100) DEFAULT NULL COMMENT '区县',
    school_name             VARCHAR(300) DEFAULT NULL COMMENT '学校名称',
    exam_type               VARCHAR(50) DEFAULT NULL COMMENT 'qb_exam_type：保留来源值',
    question_type           VARCHAR(100) DEFAULT NULL COMMENT '保留网站中文题型原值',
    difficulty              VARCHAR(20) DEFAULT NULL COMMENT 'qb_difficulty：保留网站中文原值',
    difficulty_coefficient  DECIMAL(6,4) DEFAULT NULL COMMENT '精确难度系数',
    score                   DECIMAL(8,2) DEFAULT NULL COMMENT '题目分值',
    content_html            LONGTEXT COMMENT '清洗后的题干 HTML',
    plain_text              LONGTEXT COMMENT '题目搜索文本',
    answer_html             LONGTEXT COMMENT '答案 HTML，未获得时为空',
    analysis_html           LONGTEXT COMMENT '解析 HTML，未获得时为空',
    answer_status           VARCHAR(20) NOT NULL DEFAULT 'unknown' COMMENT 'qb_answer_status：答案获取状态',
    subquestion_count       SMALLINT DEFAULT NULL COMMENT '子问题数量',
    website_time_text       VARCHAR(50) DEFAULT NULL COMMENT '来源相对时间原文',
    external_updated_at     DATETIME DEFAULT NULL COMMENT '来源更新时间（可确定时）',
    assemble_count          INT DEFAULT NULL COMMENT '组卷次数',
    reference_count         INT DEFAULT NULL COMMENT '引用试卷数量',
    reference_papers_json   JSON DEFAULT NULL COMMENT '引用试卷展开 JSON',
    is_fresh                CHAR(1) DEFAULT NULL COMMENT 'sys_yes_no：是否新题',
    content_hash            CHAR(64) DEFAULT NULL COMMENT '规范化题目文本 SHA-256',
    raw_data_json           JSON DEFAULT NULL COMMENT '来源未拆字段 JSON',
    last_sync_batch_id      BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at            DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    status                  CHAR(1) NOT NULL DEFAULT '0' COMMENT 'sys_normal_disable：0 正常，1 停用',
    create_time             DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time             DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (question_id),
    UNIQUE KEY uk_qb_question_provider_external (source_provider, external_question_id),
    KEY idx_qb_question_grade_term (grade, term),
    KEY idx_qb_question_type_difficulty (question_type, difficulty),
    KEY idx_qb_question_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库题目当前数据';

CREATE TABLE IF NOT EXISTS qb_question_catalog (
    relation_id          BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    question_id          BIGINT NOT NULL COMMENT '题目本地 ID',
    catalog_id           BIGINT NOT NULL COMMENT '目录节点本地 ID',
    relation_type        VARCHAR(30) NOT NULL DEFAULT 'query_catalog' COMMENT 'query_catalog 或 knowledge',
    evidence_type        VARCHAR(30) NOT NULL DEFAULT 'query_membership' COMMENT 'query_membership 或 provider_asserted',
    sort_order           INT NOT NULL DEFAULT 0 COMMENT '来源关系顺序',
    last_sync_batch_id   BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at         DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    create_time          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (relation_id),
    UNIQUE KEY uk_qb_question_catalog (question_id, catalog_id, relation_type, evidence_type),
    KEY idx_qb_question_catalog_catalog (catalog_id, question_id),
    CONSTRAINT chk_qb_question_catalog_relation_type CHECK (relation_type IN ('query_catalog', 'knowledge')),
    CONSTRAINT chk_qb_question_catalog_evidence_type CHECK (evidence_type IN ('query_membership', 'provider_asserted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题目目录当前关系';

CREATE TABLE IF NOT EXISTS qb_question_tag (
    tag_id              BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    question_id         BIGINT NOT NULL COMMENT '题目本地 ID',
    tag_type            VARCHAR(30) NOT NULL COMMENT 'scene、category、exam_method、source_feature',
    tag_name            VARCHAR(100) NOT NULL COMMENT '网站标签中文原值，未知值保留原文',
    evidence_type       VARCHAR(30) NOT NULL DEFAULT 'provider_asserted' COMMENT 'query_membership 或 provider_asserted',
    sort_order          INT NOT NULL DEFAULT 0 COMMENT '标签顺序',
    last_sync_batch_id  BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at        DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    create_time         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (tag_id),
    UNIQUE KEY uk_qb_question_tag (question_id, tag_type, tag_name, evidence_type),
    KEY idx_qb_question_tag_type (tag_type, tag_name),
    CONSTRAINT chk_qb_question_tag_evidence_type CHECK (evidence_type IN ('query_membership', 'provider_asserted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题目标签当前关系';

CREATE TABLE IF NOT EXISTS qb_question_asset (
    asset_id             BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    question_id          BIGINT NOT NULL COMMENT '题目本地 ID',
    source_provider      VARCHAR(64) NOT NULL COMMENT '来源提供方，由同步/发布器显式提供',
    asset_key            VARCHAR(100) NOT NULL COMMENT 'HTML data-asset-key，题目内唯一',
    asset_type            VARCHAR(30) NOT NULL COMMENT 'qb_asset_type：素材类型',
    source_url            VARCHAR(1000) DEFAULT NULL COMMENT '素材来源地址',
    storage_path          VARCHAR(1000) DEFAULT NULL COMMENT '本地或对象存储路径',
    mime_type             VARCHAR(100) DEFAULT NULL COMMENT '素材 MIME 类型',
    file_name             VARCHAR(255) DEFAULT NULL COMMENT '文件名',
    file_hash             CHAR(64) DEFAULT NULL COMMENT '文件 SHA-256',
    width                 INT DEFAULT NULL COMMENT '像素宽度',
    height                INT DEFAULT NULL COMMENT '像素高度',
    sort_order            INT NOT NULL DEFAULT 0 COMMENT '素材顺序',
    download_status       VARCHAR(20) NOT NULL DEFAULT 'pending' COMMENT 'qb_asset_status：下载状态',
    error_message         VARCHAR(1000) DEFAULT NULL COMMENT '下载失败原因',
    last_sync_batch_id    BIGINT DEFAULT NULL COMMENT '最近同步批次本地 ID，仅用于追踪',
    last_seen_at          DATETIME DEFAULT NULL COMMENT '来源最近发现时间',
    create_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (asset_id),
    UNIQUE KEY uk_qb_question_asset (question_id, asset_key),
    KEY idx_qb_question_asset_file_hash (file_hash),
    KEY idx_qb_question_asset_status (download_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题目素材当前数据';

CREATE TABLE IF NOT EXISTS qb_sync_batch (
    batch_id                 BIGINT NOT NULL AUTO_INCREMENT COMMENT '本地主键',
    batch_no                 VARCHAR(128) NOT NULL COMMENT '发布批次号',
    batch_type               VARCHAR(20) NOT NULL COMMENT 'full 或 rollback',
    source_provider          VARCHAR(64) NOT NULL COMMENT '来源提供方，由发布器显式提供',
    schema_version           VARCHAR(64) NOT NULL COMMENT '数据集 schema 版本',
    artifact_uri             VARCHAR(1000) DEFAULT NULL COMMENT '发布构建物地址',
    artifact_sha256          CHAR(64) DEFAULT NULL COMMENT '发布构建物 SHA-256',
    status                   VARCHAR(30) NOT NULL DEFAULT 'building' COMMENT 'qb_batch_status 状态机',
    previous_batch_id        BIGINT DEFAULT NULL COMMENT '发布前当前批次本地 ID',
    restored_from_batch_id   BIGINT DEFAULT NULL COMMENT '回退恢复的来源批次本地 ID',
    question_count           INT NOT NULL DEFAULT 0 COMMENT '题目数量',
    catalog_count            INT NOT NULL DEFAULT 0 COMMENT '目录数量',
    tag_count                INT NOT NULL DEFAULT 0 COMMENT '标签数量',
    asset_count              INT NOT NULL DEFAULT 0 COMMENT '素材数量',
    validation_report_json   JSON DEFAULT NULL COMMENT '校验报告 JSON',
    diff_report_json         JSON DEFAULT NULL COMMENT '发布差异报告 JSON',
    error_message            VARCHAR(2000) DEFAULT NULL COMMENT '批次错误信息',
    approved_by              VARCHAR(64) DEFAULT NULL COMMENT '批准人',
    approved_at              DATETIME DEFAULT NULL COMMENT '批准时间',
    started_at               DATETIME DEFAULT NULL COMMENT '构建开始时间',
    validated_at             DATETIME DEFAULT NULL COMMENT '校验完成时间',
    published_at             DATETIME DEFAULT NULL COMMENT '发布时间',
    archived_at              DATETIME DEFAULT NULL COMMENT '归档时间',
    create_time              DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time              DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (batch_id),
    UNIQUE KEY uk_qb_sync_batch_no (batch_no),
    KEY idx_qb_sync_batch_status (status),
    CONSTRAINT chk_qb_sync_batch_type CHECK (batch_type IN ('full', 'rollback')),
    CONSTRAINT chk_qb_sync_batch_status CHECK (status IN ('building', 'validating', 'validated', 'approval_pending', 'approved', 'publishing', 'published', 'failed', 'archived', 'rolled_back'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库发布批次元数据';

CREATE TABLE IF NOT EXISTS qb_dataset_meta (
    scope_key            VARCHAR(128) NOT NULL COMMENT '数据集范围主键',
    source_provider      VARCHAR(64) NOT NULL COMMENT '来源提供方，由发布器显式提供',
    current_batch_id     BIGINT DEFAULT NULL COMMENT '当前生效批次本地 ID',
    previous_batch_id    BIGINT DEFAULT NULL COMMENT '前一生效批次本地 ID',
    schema_version       VARCHAR(64) NOT NULL COMMENT '数据集 schema 版本',
    dataset_hash         CHAR(64) DEFAULT NULL COMMENT '当前数据集 SHA-256',
    published_at         DATETIME DEFAULT NULL COMMENT '最近发布时间',
    create_time          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (scope_key),
    KEY idx_qb_dataset_meta_provider (source_provider),
    KEY idx_qb_dataset_meta_current_batch (current_batch_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库数据集发布元数据';
