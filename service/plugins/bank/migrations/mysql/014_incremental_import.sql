CREATE TABLE IF NOT EXISTS qb_question_import (
    import_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    task_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    source_provider VARCHAR(64) NOT NULL,
    local_textbook_id BIGINT NOT NULL,
    external_textbook_id VARCHAR(64) NOT NULL,
    collector_run_id BIGINT NOT NULL,
    snapshot_locked_at DATETIME NOT NULL,
    snapshot_complete SMALLINT NOT NULL,
    quality_hash CHAR(64) NOT NULL,
    identity_hash CHAR(64) NOT NULL,
    question_count INT NOT NULL,
    committed_cursor INT NOT NULL DEFAULT 0,
    batch_no INT NOT NULL DEFAULT 0,
    accepted_count INT NOT NULL DEFAULT 0,
    quarantined_count INT NOT NULL DEFAULT 0,
    stats_json JSON NOT NULL,
    status VARCHAR(20) NOT NULL,
    worker_token CHAR(64) NULL,
    lease_until DATETIME NULL,
    error_message VARCHAR(2000) NULL,
    finished_at DATETIME NULL,
    create_time DATETIME NOT NULL,
    update_time DATETIME NOT NULL,
    UNIQUE KEY uk_qb_question_import_scope_run (scope_id, collector_run_id),
    KEY idx_qb_question_import_task (task_id, import_id),
    KEY idx_qb_question_import_lease (status, lease_until),
    CONSTRAINT chk_qb_question_import_status CHECK (status IN ('running','completed','partial','failed')),
    CONSTRAINT chk_qb_question_import_cursor CHECK (committed_cursor >= 0 AND committed_cursor <= question_count)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS qb_question_import_batch (
    import_id BIGINT NOT NULL,
    batch_no INT NOT NULL,
    start_cursor INT NOT NULL,
    next_cursor INT NOT NULL,
    batch_hash CHAR(64) NOT NULL,
    accepted_count INT NOT NULL,
    quarantined_count INT NOT NULL,
    stats_json JSON NOT NULL,
    issues_json JSON NOT NULL,
    create_time DATETIME NOT NULL,
    PRIMARY KEY (import_id, batch_no),
    UNIQUE KEY uk_qb_import_batch_cursor (import_id, start_cursor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
