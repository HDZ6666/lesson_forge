-- 后台抓取任务状态。
-- 任务只编排来源采集脚本并写入 SQLite 候选库，不写入题库正式表。
CREATE TABLE IF NOT EXISTS qb_sync_job (
    run_id                  BIGINT NOT NULL AUTO_INCREMENT COMMENT '同步任务主键',
    status                  VARCHAR(20) NOT NULL DEFAULT 'queued' COMMENT 'queued/starting/running/cancelling/completed/failed/blocked/cancelled',
    phase                   VARCHAR(30) NOT NULL DEFAULT 'metadata' COMMENT 'metadata/catalogs_questions/completed/failed/blocked/cancelled',
    acknowledge_source_policy CHAR(1) NOT NULL DEFAULT 'N' COMMENT '是否确认来源站规则/授权范围',
    options_json             JSON NOT NULL COMMENT '服务端固定执行选项快照',
    total_versions          INT NOT NULL DEFAULT 0 COMMENT '本次发现版本数量',
    completed_versions      INT NOT NULL DEFAULT 0 COMMENT '已处理版本数量',
    total_textbooks          INT NOT NULL DEFAULT 0 COMMENT '本次发现教材数量',
    completed_textbooks      INT NOT NULL DEFAULT 0 COMMENT '已完成教材数量',
    catalog_count            INT NOT NULL DEFAULT 0 COMMENT '候选目录数量',
    question_count           INT NOT NULL DEFAULT 0 COMMENT '候选题目数量',
    current_textbook_id     VARCHAR(128) DEFAULT NULL COMMENT '当前来源教材 ID',
    current_textbook_name   VARCHAR(300) DEFAULT NULL COMMENT '当前教材名称',
    progress_percent        DECIMAL(6,2) NOT NULL DEFAULT 0 COMMENT '任务进度百分比',
    log_tail                LONGTEXT COMMENT '长度受限的执行日志尾部',
    error_message           VARCHAR(2000) DEFAULT NULL COMMENT '失败或中断原因',
    process_id              BIGINT DEFAULT NULL COMMENT '当前 Node 子进程 PID',
    worker_token            VARCHAR(64) DEFAULT NULL COMMENT '执行任务的后端 worker 标识',
    active_slot             CHAR(1) DEFAULT NULL COMMENT '活动任务互斥槽，终态置空',
    created_by              VARCHAR(64) DEFAULT NULL COMMENT '发起人',
    started_at              DATETIME DEFAULT NULL COMMENT '开始执行时间',
    finished_at             DATETIME DEFAULT NULL COMMENT '完成/终止时间',
    create_time             DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time             DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (run_id),
    UNIQUE KEY uk_qb_sync_job_active_slot (active_slot),
    KEY idx_qb_sync_job_status (status),
    KEY idx_qb_sync_job_create_time (create_time),
    CONSTRAINT chk_qb_sync_job_status CHECK (status IN ('queued', 'starting', 'running', 'cancelling', 'completed', 'failed', 'blocked', 'cancelled')),
    CONSTRAINT chk_qb_sync_job_phase CHECK (phase IN ('metadata', 'catalogs_questions', 'completed', 'failed', 'blocked', 'cancelled')),
    CONSTRAINT chk_qb_sync_job_ack CHECK (acknowledge_source_policy IN ('Y', 'N'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='题库来源同步后台任务';
